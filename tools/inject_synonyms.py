lines = [l for l in EXTRA_GROUPS.splitlines() if l.strip()]

src = open(TARGET, encoding='utf-8').read()

marker = "SYN = {}\n"
if marker not in src:
    sys.exit('找不到 SYN = {} 标记')

block = []
for line in lines:
    items = [x.strip() for x in line.replace(',', '|').split('|') if x.strip()]
    if len(items) < 2:
        continue
    block.append('    [' + ', '.join("'%s'" % x for x in items) + '],')

addition = (
    "\n# ---- 扩展同义词表（由 tools/syn_extra.txt 注入，覆盖常见同义改写）----\n"
    "SYN_GROUPS += [\n" + '\n'.join(block) + "\n]\n"
)

if '扩展同义词表' in src:
    # 幂等：替换已有扩展块
    src = re.sub(r'\n# ---- 扩展同义词表.*?\n\]\n', addition, src, flags=re.S)
else:
    src = src.replace(marker, marker + addition, 1)

open(TARGET, 'w', encoding='utf-8').write(src)
print('注入同义词组：%d 条' % len(block))
