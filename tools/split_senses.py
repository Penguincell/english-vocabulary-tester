# 用于判断两个义项是否属于同一概念簇
CLUSTER = []   # [(concept_id, [term,...])]


def cluster_of(word, text, terms=None):
    """义项所属概念簇 id。

    概念簇直接来自「合并后的词义核心」——一个簇 = 一个选项。
    这样同义改写（好奇的/有求知欲的）已在合并阶段处理，簇天然唯一。
    CONCEPTS 表只作为人工兜底：把同义但字面差太远的词硬拉进同一簇。
    """
    cores = [norm_core(t) for t in (terms or [text])]
    for cid, group_terms in CONCEPTS.get(word.lower(), []):
        pool = {norm_core(x) for x in group_terms.split()}
        if any(c in pool for c in cores):
            return '%s:%s' % (word.lower(), cid)
    return '%s:term:%s' % (word.lower(), cores[0] if cores else norm_core(text))


def broad_pos(p):
    p = p.rstrip('.')
    return 'v' if p in ('vt', 'vi') else ('n' if p == 'pl' else p)


def strip_parens(t):
    return PAREN.sub('', t).strip(' ，,、。')


def split_terms(text):
    """按逗号/顿号/分号拆分，但括号内的逗号不拆；丢弃残缺括号片段。"""
    text = text.replace('，', ',')
    terms = []
    buf = ''
    depth = 0
    for ch in text:
        if ch in '([（【':
            depth += 1
            buf += ch
        elif ch in ')]）】':
            depth = max(0, depth - 1)
            buf += ch
        elif ch in ',、;；' and depth == 0:
            if buf.strip():
                terms.append(buf.strip())
            buf = ''
        else:
            buf += ch
    if buf.strip():
        terms.append(buf.strip())
    out = []
    for t in terms:
        t = t.strip(' 。,、;；')
        if not t:
            continue
        # 丢掉括号不配对的碎片
        if t.count('(') + t.count('（') != t.count(')') + t.count('）'):
            continue
        out.append(t)
    return out


def norm_core(t):
    """义项的「词义核心」：去括注、去词性、去「的/地」后缀、去空格与省略号。"""
    t = strip_parens(t)
    t = re.sub(r'[（(][^）)]*[）)]', '', t)
    t = re.sub(r'\.{2,}|…+|·+', '', t)
    t = re.sub(r'\s+', '', t)
    t = re.sub(r'^(?:使|被|把|给|为|用)', '', t)
    t = re.sub(r'[的地得了]+$', '', t)
    t = re.sub(r'(n|v|vt|vi|adj|adv|prep|conj|pron|num|art|interj|aux|det)\.', '', t)
    return t


def char_ratio(a, b):
    sa, sb = set(a), set(b)
    if not sa or not sb:
        return 0.0
    return len(sa & sb) / min(len(sa), len(sb))


def same_sense(a, b):
    """判断两个义项是否属于同一个意思。

    合并得比较激进——宁可按同一意义合并，也不要拆成两个选项：
    - 完全相等（忽略词性、的/地、空格、省略号）
    - 命中同义词表
    - 一个是另一个的包含（长度差 <= 4）
    - 字面高度重合（>= 60%），覆盖「青年 / 青春，年轻」这类同义改写
    """
    a0, b0 = norm_core(a), norm_core(b)
    if not a0 or not b0:
        return False
    if a0 == b0:
        return True
    if b0 in SYN.get(a0, ()) or a0 in SYN.get(b0, ()):
        return True
    short, long_ = (a0, b0) if len(a0) <= len(b0) else (b0, a0)
    # 多字包含：短词 >= 2 字，长度差不夸张
    if len(short) >= 2 and short in long_ and len(long_) - len(short) <= 4:
        return True
    # 单字根：只认「以它开头的短词」，如「光 / 日光」「灯 / 灯具」；
    # 不认「关键」里的「键」这种词素，避免把不同义项吃掉
    if len(short) == 1 and long_.startswith(short) and len(long_) <= 3:
        return True
    if len(short) >= 2 and char_ratio(a0, b0) >= 0.6:
        return True
    if len(short) >= 2 and (long_.startswith(short) or long_.endswith(short)) \
            and len(long_) - len(short) <= 3:
        return True
    return False


def tag_of(terms):
    joined = '，'.join(terms)
    if PAREN.search(joined):
        return 'specific'
    for t in terms:
        if strip_parens(t) in ABSTRACT_HINT:
            return 'core'
    return 'common' if len(joined) > 8 else 'core'


def build(entry):
    marked = re.sub(r'(?<![A-Za-z])(' + POS_ALT + r')\.', r'\n\1.', entry['meaning'])
    segments = []
    for chunk in marked.split('\n'):
        chunk = chunk.strip()
        if not chunk:
            continue
        m = re.match(r'^(' + POS_ALT + r')\.\s*(.*)$', chunk)
        if m:
            segments.append([m.group(1), m.group(2)])
        elif segments:
            segments[-1][1] += ' ' + chunk
        else:
            segments.append(['', chunk])
    # 合并同一词性的多个段，避免「vi.运行」被拆到 vt. 段里
    merged_pos = []
    for pos, txt in segments:
        if merged_pos and merged_pos[-1][0] == pos:
            merged_pos[-1][1] += '，' + txt
        else:
            merged_pos.append([pos, txt])
    segments = merged_pos

    groups = []
    for pos, txt in segments:
        terms = split_terms(txt)
        for t in terms:
            # 去掉人名/地名残留
            if re.search(r'人名|地名', t):
                continue
            if re.fullmatch(r'[（(]?[A-Za-z][^）)]*[）)]?', t):
                continue
            t = re.sub(r'\s+', ' ', t).strip()
            if not t:
                continue
            g = None
            for cand in groups:
                # 不再限制词性：vt.摇动 和 n.摇动 是同一个意思
                if same_sense(cand['terms'][0], t):
                    g = cand
                    break
            if g:
                if t not in g['terms']:
                    g['terms'].append(t)
                # 词性取「更具体」的那个：vi./vt. 比 v. 精确，adj. 比空精确
                if pos and (not g['pos'] or (pos in ('vt', 'vi') and g['pos'] in ('v.', '', 'v'))):
                    g['pos'] = pos + '.'
            else:
                groups.append({'pos': pos + '.' if pos else '',
                               'posb': broad_pos(pos) if pos else '',
                               'terms': [t],
                               'order': len(groups)})
    for g in groups:
        g['text'] = '，'.join(g['terms'])
        g['tag'] = tag_of(g['terms'])
        g['abstract'] = any(strip_parens(t) in ABSTRACT_HINT for t in g['terms'])
        g['concept'] = cluster_of(entry['word'], g['text'], g['terms'])
    return groups


def rank(groups):
    """保留原词典顺序作为「常考程度」的第一依据；专指义后移。"""
    def key(g):
        t = 1 if g['tag'] == 'specific' else 0
        return (t, g['order'])
    return sorted(groups, key=key)


def main():
    vocab = json.load(open(SRC, encoding='utf-8'))
    out = []
    for e in vocab:
        groups = rank(build(e))
        if not groups:
            continue
        out.append({
            'id': e['id'],
            'word': e['word'],
            'short': e['short'],
            'groups': [{'pos': g['pos'], 'text': g['text'], 'terms': g['terms'], 'concept': g['concept'],
                        'tag': g['tag'], 'abstract': g['abstract'], 'order': g['order']}
                       for g in groups],
        })
    json.dump(out, open(OUT, 'w', encoding='utf-8'), ensure_ascii=False, separators=(',', ':'))
    print('wrote', OUT, len(out), 'words')

    for w in ('key', 'channel', 'bank', 'run', 'light', 'mean', 'spring', 'soil'):
        for e in out:
            if e['word'].lower() == w:
                print('==', e['word'])
                for g in e['groups']:
                    print('   [%s]%s %s' % (g['tag'], g['pos'], g['text']))


if __name__ == '__main__':
    main()
